-- שחרור רדיוס הנוכחות מהערך הקשיח של 15 מ׳
--
-- מסך ההגדרות שמר עד היום location_radius_m = 15 בכל שמירת כתובת, בלי דרך
-- לשנות אותו. 15 מ׳ קטן מדיוק המיקום שדפדפן מסוגל לספק, ולכן עובדים שעמדו
-- בעסק נחסמו. עכשיו המנהל בוחר את הרדיוס במסך ההגדרות; כאן מוחזרות השורות
-- שנתקעו על הערך הקשיח לברירת המחדל של 100 מ׳.
--
-- אין שינוי סכימה — העמודה כבר מוגדרת `integer default 100`.

update public.businesses
set location_radius_m = 100
where location_radius_m is null or location_radius_m = 15;
